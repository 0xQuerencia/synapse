//! A real local caller for signed policy inspection and cache lifecycle.
//! `fixture` creates original synthetic cache-test data, not inference weights.
use anyhow::{Result, bail, ensure};
use sha2::{Digest, Sha256};
use std::{
    fs,
    path::Path,
    time::{SystemTime, UNIX_EPOCH},
};
use synapse_core::{
    NodeIdentity,
    catalog::{
        CatalogStatus, CatalogUse, ModelCache, ModelRights, SignedModelRecord, TrustRoot,
        TrustedPublisher, inspect_record, read_catalog_json, read_trust_root,
    },
    inference::model_loader::{ModelArtifact, ModelManifest},
};

fn purpose(value: &str) -> Result<CatalogUse> {
    match value {
        "local" => Ok(CatalogUse::LocalInference),
        "host" => Ok(CatalogUse::RemoteHosting),
        "redistribute" => Ok(CatalogUse::Redistribution),
        _ => bail!("purpose must be local, host, or redistribute"),
    }
}
fn output(value: &impl serde::Serialize) -> Result<()> {
    println!("{}", serde_json::to_string_pretty(value)?);
    Ok(())
}
fn now() -> Result<u64> {
    Ok(SystemTime::now().duration_since(UNIX_EPOCH)?.as_secs())
}

fn fixture(path: &Path, inference: bool) -> Result<()> {
    ensure!(!path.exists(), "fixture destination must not exist");
    #[cfg(unix)]
    {
        use std::os::unix::fs::DirBuilderExt;
        fs::DirBuilder::new().mode(0o700).create(path)?;
    }
    #[cfg(not(unix))]
    {
        bail!("fixture/cache example currently requires Unix");
    }
    let source = path.join("source");
    fs::create_dir(&source)?;
    let files: [(&str, &[u8]); 3] = if inference {
        [
            (
                "config.json",
                include_bytes!("../tests/fixtures/tiny-llama/config.json"),
            ),
            (
                "tokenizer.json",
                include_bytes!("../tests/fixtures/tiny-llama/tokenizer.json"),
            ),
            (
                "model.safetensors",
                include_bytes!("../tests/fixtures/tiny-llama/model.safetensors"),
            ),
        ]
    } else {
        [
            ("config.json", b"{}"),
            ("tokenizer.json", b"{}"),
            (
                "model.safetensors",
                b"Original Synapse catalog fixture; NOT inference weights.\n",
            ),
        ]
    };
    let mut artifacts = Vec::new();
    for (name, bytes) in files {
        fs::write(source.join(name), bytes)?;
        artifacts.push(ModelArtifact {
            filename: name.into(),
            size_bytes: bytes.len() as u64,
            sha256: format!("{:x}", Sha256::digest(bytes)),
        });
    }
    let identity = NodeIdentity::load_or_create_at(&path.join("publisher.key"))?;
    let issued = now()?;
    let mut record = SignedModelRecord { schema_version: 1, publisher: String::new(), public_key: Vec::new(), issued_at_unix: issued, expires_at_unix: issued + 86400, status: CatalogStatus::Approved, license: "MIT (original synthetic test data)".into(), rights: ModelRights { local_inference: true, remote_hosting: false, redistribution: false }, provenance: "Original deterministic bytes generated by the Synapse catalog example for cache tests; not a usable language model".into(), manifest: ModelManifest { schema_version: 1, model_id: "synapse/catalog-test-fixture".into(), revision: "fixture-v1".into(), weights: "model.safetensors".into(), artifacts }, signature: Vec::new() };
    if inference {
        record.manifest.model_id = "synapse/tiny-llama-fixture".into();
        record.provenance = "Original deterministic Synapse tiny Llama fixture; random weights and meaningless text, for offline inference mechanics only".into();
    }
    record.sign(&identity)?;
    let trust = TrustRoot {
        publishers: vec![TrustedPublisher {
            peer_id: identity.peer_id().to_string(),
            public_key: identity.public_key_bytes(),
        }],
        ..TrustRoot::default()
    };
    fs::write(
        path.join("record.json"),
        serde_json::to_vec_pretty(&record)?,
    )?;
    fs::write(path.join("trust.json"), serde_json::to_vec_pretty(&trust)?)?;
    fs::write(
        source.join("manifest.json"),
        serde_json::to_vec_pretty(&record.manifest)?,
    )?;
    output(&inspect_record(
        &record,
        &trust,
        CatalogUse::LocalInference,
        issued,
    )?)
}

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args
        .iter()
        .map(String::as_str)
        .collect::<Vec<_>>()
        .as_slice()
    {
        ["fixture", directory] => fixture(Path::new(directory), false),
        ["inference-fixture", directory] => fixture(Path::new(directory), true),
        ["inspect", record, trust, usage] => {
            let record: SignedModelRecord = read_catalog_json(Path::new(record))?;
            let trust = read_trust_root(Path::new(trust))?;
            output(&inspect_record(&record, &trust, purpose(usage)?, now()?)?)
        }
        ["import", source, record, trust, cache, quota, usage] => {
            let record: SignedModelRecord = read_catalog_json(Path::new(record))?;
            let trust = read_trust_root(Path::new(trust))?;
            let cache = ModelCache::open(Path::new(cache), quota.parse()?)?;
            output(&cache.import_model(
                Path::new(source),
                &record,
                &trust,
                purpose(usage)?,
                now()?,
            )?)
        }
        ["verify", digest, trust, cache, quota, usage] => {
            let trust = read_trust_root(Path::new(trust))?;
            let cache = ModelCache::open(Path::new(cache), quota.parse()?)?;
            let pin = cache.verify_model(digest, &trust, purpose(usage)?, now()?)?;
            output(&pin.entry)
        }
        ["prune", cache, quota, target] => {
            let cache = ModelCache::open(Path::new(cache), quota.parse()?)?;
            output(&cache.prune(target.parse()?)?)
        }
        _ => bail!(
            "usage:\n  catalog fixture NEW_DIRECTORY\n  catalog inference-fixture NEW_DIRECTORY\n  catalog inspect RECORD TRUST local|host|redistribute\n  catalog import SOURCE RECORD TRUST CACHE QUOTA_BYTES local|host|redistribute\n  catalog verify DIGEST TRUST CACHE QUOTA_BYTES local|host|redistribute\n  catalog prune CACHE QUOTA_BYTES TARGET_BYTES\n\nNothing downloads, changes global trust, or starts inference. The optional inference fixture has original random weights and produces meaningless text."
        ),
    }
}
